-- Software Factory Hub: initial schema. PostgreSQL is the system of record for everything here.
-- Redis holds only queues, pub/sub and short-lived caches, all reconstructible from these tables.

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL,
  display_name text NOT NULL,
  webauthn_user_handle bytea NOT NULL UNIQUE, -- 32 random bytes, generated by the app
  disabled_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower_idx ON users (lower(email));

CREATE TABLE passkey_credentials (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  credential_id bytea NOT NULL UNIQUE,
  public_key bytea NOT NULL,
  sign_count bigint NOT NULL DEFAULT 0,
  transports text[] NOT NULL DEFAULT '{}',
  aaguid text,
  device_type text,
  backed_up boolean NOT NULL DEFAULT false,
  label text,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz
);
CREATE INDEX passkey_credentials_user_idx ON passkey_credentials (user_id);

CREATE TABLE sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  last_seen_at timestamptz,
  user_agent text
);
CREATE INDEX sessions_user_idx ON sessions (user_id);
CREATE INDEX sessions_expiry_idx ON sessions (expires_at);

CREATE TABLE organisations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE memberships (
  org_id uuid NOT NULL REFERENCES organisations(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('owner','admin','member','viewer')),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, user_id)
);
CREATE INDEX memberships_user_idx ON memberships (user_id);

CREATE TABLE factories (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id uuid NOT NULL REFERENCES organisations(id) ON DELETE CASCADE,
  name text NOT NULL,
  owner_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
  version text,
  status text NOT NULL DEFAULT 'registered' CHECK (status IN ('registered','active','disabled')),
  last_seen_at timestamptz,
  metadata jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, name)
);

-- Only a keyed hash of the factory token is stored; the token is shown once at registration.
CREATE TABLE factory_credentials (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  factory_id uuid NOT NULL REFERENCES factories(id) ON DELETE CASCADE,
  secret_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz,
  revoked_at timestamptz,
  last_used_at timestamptz
);
CREATE INDEX factory_credentials_factory_idx ON factory_credentials (factory_id);

CREATE TABLE factory_permissions (
  factory_id uuid NOT NULL REFERENCES factories(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  permission text NOT NULL CHECK (permission IN ('view','command','manage')),
  granted_by uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (factory_id, user_id, permission)
);

CREATE TABLE projects (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  factory_id uuid NOT NULL REFERENCES factories(id) ON DELETE CASCADE,
  external_id text NOT NULL,
  name text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}',
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (factory_id, external_id)
);

CREATE TABLE jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  factory_id uuid NOT NULL REFERENCES factories(id) ON DELETE CASCADE,
  project_id uuid REFERENCES projects(id) ON DELETE SET NULL,
  external_id text NOT NULL,
  title text,
  stage text,
  status text,
  workflow_id text,
  metadata jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (factory_id, external_id)
);
CREATE INDEX jobs_project_idx ON jobs (project_id);

CREATE TABLE workflows (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  factory_id uuid NOT NULL REFERENCES factories(id) ON DELETE CASCADE,
  external_id text NOT NULL,
  name text NOT NULL,
  version text,
  definition jsonb NOT NULL DEFAULT '{}',
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (factory_id, external_id)
);

-- (factory_id, event_id) makes event ingestion idempotent: a factory can safely resend a batch.
CREATE TABLE factory_events (
  id bigserial PRIMARY KEY,
  factory_id uuid NOT NULL REFERENCES factories(id) ON DELETE CASCADE,
  event_id text NOT NULL,
  job_id uuid REFERENCES jobs(id) ON DELETE SET NULL,
  type text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}',
  occurred_at timestamptz NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (factory_id, event_id)
);
CREATE INDEX factory_events_factory_time_idx ON factory_events (factory_id, occurred_at DESC);

-- Command lifecycle:
--   pending -> queued -> delivered -> acknowledged -> succeeded | failed
--   pending|queued|delivered -> expired | revoked      (never executed)
--   acknowledged -> unknown   (lease lost mid-execution of a NON-idempotent command: never re-run)
CREATE TABLE remote_commands (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id uuid NOT NULL REFERENCES organisations(id) ON DELETE CASCADE,
  factory_id uuid NOT NULL REFERENCES factories(id) ON DELETE CASCADE,
  requested_by uuid REFERENCES users(id) ON DELETE SET NULL,
  type text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}',
  client_key text,                          -- caller-supplied dedupe key
  repeatable boolean NOT NULL DEFAULT false, -- safe to run twice? if not, never redelivered after ack
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','queued','delivered','acknowledged','succeeded','failed','expired','revoked','unknown')),
  attempts int NOT NULL DEFAULT 0,
  lease_token uuid,
  lease_expires_at timestamptz,
  expires_at timestamptz NOT NULL,
  delivered_at timestamptz,
  acknowledged_at timestamptz,
  completed_at timestamptz,
  revoked_at timestamptz,
  result jsonb,
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX remote_commands_client_key_idx ON remote_commands (factory_id, client_key) WHERE client_key IS NOT NULL;
CREATE INDEX remote_commands_claim_idx ON remote_commands (factory_id, created_at) WHERE status IN ('pending','queued','delivered');
CREATE INDEX remote_commands_open_idx ON remote_commands (status, expires_at) WHERE status IN ('pending','queued','delivered','acknowledged');

-- Transactional outbox: written in the same transaction as the command, drained by the relay.
CREATE TABLE outbox (
  id bigserial PRIMARY KEY,
  topic text NOT NULL,
  aggregate_id uuid NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}',
  available_at timestamptz NOT NULL DEFAULT now(),
  dispatched_at timestamptz,
  attempts int NOT NULL DEFAULT 0,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX outbox_undispatched_idx ON outbox (available_at) WHERE dispatched_at IS NULL;

CREATE TABLE audit_events (
  id bigserial PRIMARY KEY,
  org_id uuid REFERENCES organisations(id) ON DELETE SET NULL,
  actor_type text NOT NULL CHECK (actor_type IN ('user','factory','system')),
  actor_id uuid,
  action text NOT NULL,
  target_type text,
  target_id uuid,
  detail jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_events_org_time_idx ON audit_events (org_id, created_at DESC);

CREATE TABLE push_subscriptions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE,
  p256dh text NOT NULL,
  auth text NOT NULL,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_success_at timestamptz,
  disabled_at timestamptz
);
CREATE INDEX push_subscriptions_user_idx ON push_subscriptions (user_id);

CREATE TABLE notification_preferences (
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  PRIMARY KEY (user_id, event_type)
);

CREATE TABLE notification_deliveries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  subscription_id uuid REFERENCES push_subscriptions(id) ON DELETE SET NULL,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  event_id bigint REFERENCES factory_events(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent','failed','gone')),
  attempts int NOT NULL DEFAULT 0,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz
);
CREATE INDEX notification_deliveries_pending_idx ON notification_deliveries (created_at) WHERE status = 'pending';
